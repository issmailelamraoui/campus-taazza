-- Marketplace contact threads remain private to the seller and original buyer.
CREATE TABLE market_request_replies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id INTEGER NOT NULL REFERENCES market_requests(id) ON DELETE CASCADE,
 author_id INTEGER NOT NULL REFERENCES users(id),
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 2000),
 created_at TEXT NOT NULL
);
CREATE INDEX market_request_thread ON market_request_replies(request_id,id);
