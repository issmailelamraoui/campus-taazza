-- Migration 012 is immutable once applied. These feedback additions therefore
-- belong in a new migration; existing accounts, tickets and uploads survive.
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS filiere_id TEXT REFERENCES filieres(id);
CREATE TABLE IF NOT EXISTS contact_attachments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contact_id INTEGER NOT NULL REFERENCES contacts(id),
 author_id INTEGER NOT NULL REFERENCES users(id),
 filename TEXT NOT NULL, object_key TEXT NOT NULL, sha256 TEXT NOT NULL,
 size INTEGER NOT NULL CHECK(size>0 AND size<=20971520), mime TEXT NOT NULL,
 created_at TEXT NOT NULL, UNIQUE(contact_id,sha256)
);
CREATE INDEX IF NOT EXISTS contact_attachments_thread ON contact_attachments(contact_id,id);
