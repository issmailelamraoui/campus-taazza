CREATE TABLE campus_questions (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 faculty_id TEXT NOT NULL REFERENCES faculties(id), filiere_id TEXT NOT NULL REFERENCES filieres(id),
 author_id INTEGER NOT NULL REFERENCES users(id), title TEXT NOT NULL, body TEXT NOT NULL, module TEXT NOT NULL DEFAULT '',
 resource_id INTEGER REFERENCES resources(id), source_page INTEGER CHECK(source_page>0),
 accepted_answer_id INTEGER, removed BOOLEAN NOT NULL DEFAULT FALSE, created_at TEXT NOT NULL,
 FOREIGN KEY(filiere_id,faculty_id) REFERENCES filieres(id,faculty_id)
);
CREATE TABLE campus_answers (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, question_id INTEGER NOT NULL REFERENCES campus_questions(id),
 author_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, created_at TEXT NOT NULL,
 removed BOOLEAN NOT NULL DEFAULT FALSE
);
ALTER TABLE campus_questions ADD CONSTRAINT accepted_campus_answer FOREIGN KEY(accepted_answer_id) REFERENCES campus_answers(id);
CREATE TABLE campus_comments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, answer_id INTEGER NOT NULL REFERENCES campus_answers(id),
 author_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE campus_votes (
 answer_id INTEGER NOT NULL REFERENCES campus_answers(id), user_id INTEGER NOT NULL REFERENCES users(id),
 value INTEGER NOT NULL CHECK(value IN (-1,1)), created_at TEXT NOT NULL, PRIMARY KEY(answer_id,user_id)
);
CREATE INDEX campus_question_scope ON campus_questions(faculty_id,filiere_id,created_at);
CREATE INDEX campus_answer_question ON campus_answers(question_id,created_at);

CREATE TABLE close_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, faculty_id TEXT NOT NULL REFERENCES faculties(id),
 filiere_id TEXT NOT NULL REFERENCES filieres(id), requester_id INTEGER NOT NULL REFERENCES users(id),
 title TEXT NOT NULL, topic TEXT NOT NULL, module TEXT NOT NULL DEFAULT '', resource_id INTEGER REFERENCES resources(id),
 source_page INTEGER CHECK(source_page>0), excerpt TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','accepted','closed')), created_at TEXT NOT NULL,
 FOREIGN KEY(filiere_id,faculty_id) REFERENCES filieres(id,faculty_id)
);
CREATE TABLE close_rooms (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id INTEGER NOT NULL UNIQUE REFERENCES close_requests(id),
 requester_id INTEGER NOT NULL REFERENCES users(id), helper_id INTEGER NOT NULL REFERENCES users(id),
 CHECK(requester_id<>helper_id), created_at TEXT NOT NULL, closed_at TEXT,
 board_revision INTEGER NOT NULL DEFAULT 0, requester_consent BOOLEAN NOT NULL DEFAULT FALSE,
 helper_consent BOOLEAN NOT NULL DEFAULT FALSE, recording BOOLEAN NOT NULL DEFAULT FALSE,
 recording_started_at TEXT, recording_expires_at TEXT, help_rating TEXT CHECK(help_rating IN ('helpful','very_helpful','not_helpful'))
);
CREATE TABLE close_messages (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id INTEGER NOT NULL REFERENCES close_rooms(id),
 author_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, resource_id INTEGER REFERENCES resources(id),
 source_page INTEGER CHECK(source_page>0), client_id TEXT NOT NULL, created_at TEXT NOT NULL,
 UNIQUE(room_id,author_id,client_id)
);
CREATE TABLE close_board (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, room_id INTEGER NOT NULL REFERENCES close_rooms(id),
 revision INTEGER NOT NULL, operation JSONB NOT NULL, recorded BOOLEAN NOT NULL DEFAULT FALSE, created_at TEXT NOT NULL,
 UNIQUE(room_id,revision)
);
CREATE INDEX close_request_scope ON close_requests(faculty_id,filiere_id,status,created_at);
CREATE INDEX close_board_room ON close_board(room_id,revision);
CREATE TABLE study_matches (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
 module TEXT NOT NULL, topic TEXT NOT NULL, availability TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE study_match_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, requester_id INTEGER NOT NULL REFERENCES users(id),
 recipient_id INTEGER NOT NULL REFERENCES users(id), CHECK(requester_id<>recipient_id),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','declined')),
 created_at TEXT NOT NULL, UNIQUE(requester_id,recipient_id)
);
CREATE TABLE revision_groups (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, faculty_id TEXT NOT NULL REFERENCES faculties(id),
 filiere_id TEXT NOT NULL REFERENCES filieres(id), owner_id INTEGER NOT NULL REFERENCES users(id),
 title TEXT NOT NULL, module TEXT NOT NULL, created_at TEXT NOT NULL, closed BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(filiere_id,faculty_id) REFERENCES filieres(id,faculty_id)
);
CREATE TABLE revision_members (
 group_id INTEGER NOT NULL REFERENCES revision_groups(id), user_id INTEGER NOT NULL REFERENCES users(id),
 joined_at TEXT NOT NULL, PRIMARY KEY(group_id,user_id)
);
CREATE TABLE revision_messages (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, group_id INTEGER NOT NULL REFERENCES revision_groups(id),
 author_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, resource_id INTEGER REFERENCES resources(id),
 created_at TEXT NOT NULL
);
CREATE TABLE market_listings (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, faculty_id TEXT NOT NULL REFERENCES faculties(id),
 seller_id INTEGER NOT NULL REFERENCES users(id), title TEXT NOT NULL, body TEXT NOT NULL,
 category TEXT NOT NULL CHECK(category IN ('books','calculators','supplies','equipment')),
 price INTEGER CHECK(price>=0 AND price<=10000000), image_resource_id INTEGER REFERENCES resources(id),
 status TEXT NOT NULL DEFAULT 'available' CHECK(status IN ('available','reserved','sold','removed')), created_at TEXT NOT NULL
);
CREATE TABLE market_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, listing_id INTEGER NOT NULL REFERENCES market_listings(id),
 author_id INTEGER NOT NULL REFERENCES users(id), body TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE campus_reports (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, faculty_id TEXT NOT NULL REFERENCES faculties(id),
 reporter_id INTEGER NOT NULL REFERENCES users(id), target_type TEXT NOT NULL CHECK(target_type IN ('question','answer','room','listing')),
 target_id INTEGER NOT NULL, reason TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved','dismissed')),
 created_at TEXT NOT NULL, UNIQUE(reporter_id,target_type,target_id)
);
CREATE INDEX market_faculty ON market_listings(faculty_id,status,created_at);
CREATE INDEX campus_report_faculty ON campus_reports(faculty_id,status);
