-- Manual page mappings remain distinct from transient lexical suggestions.
CREATE TABLE document_relations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exercise_resource_id INTEGER NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
  exercise_version INTEGER NOT NULL CHECK (exercise_version > 0),
  exercise_sha256 TEXT NOT NULL CHECK (length(exercise_sha256)=64),
  exercise_page INTEGER NOT NULL CHECK (exercise_page BETWEEN 1 AND 500),
  course_resource_id INTEGER NOT NULL REFERENCES resources(id) ON DELETE CASCADE,
  course_version INTEGER NOT NULL CHECK (course_version > 0),
  course_sha256 TEXT NOT NULL CHECK (length(course_sha256)=64),
  course_page INTEGER NOT NULL CHECK (course_page BETWEEN 1 AND 500),
  reason TEXT NOT NULL CHECK (length(reason) BETWEEN 8 AND 2000),
  proposer_id INTEGER NOT NULL REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','verified','rejected')),
  reviewed_by INTEGER REFERENCES users(id), reviewed_at TEXT,
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  CHECK (exercise_resource_id<>course_resource_id),
  UNIQUE(exercise_resource_id,exercise_version,exercise_page,course_resource_id,course_version,course_page)
);
CREATE INDEX document_relations_exercise ON document_relations(exercise_resource_id,exercise_version,status);
