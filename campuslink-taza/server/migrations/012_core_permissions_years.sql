-- Additive: existing profiles, files, auth bindings and unknown material years survive.
CREATE TABLE platform_owner (
  singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id), established_at TEXT NOT NULL
);
INSERT INTO platform_owner (user_id,established_at)
SELECT min(id),CURRENT_TIMESTAMP::text FROM users WHERE role='global_admin'
HAVING count(*)=1;
CREATE TABLE scoped_appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id), appointed_by INTEGER NOT NULL REFERENCES users(id),
  faculty_id TEXT NOT NULL REFERENCES faculties(id), filiere_id TEXT REFERENCES filieres(id),
  capabilities JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(capabilities)='array'),
  created_at TEXT NOT NULL, revoked_at TEXT,
  FOREIGN KEY (filiere_id,faculty_id) REFERENCES filieres(id,faculty_id)
);
CREATE INDEX appointments_active_user ON scoped_appointments(user_id) WHERE revoked_at IS NULL;
-- Preserve existing moderation/support powers, without inventing cross-semester uploads.
INSERT INTO scoped_appointments (user_id,appointed_by,faculty_id,capabilities,created_at)
SELECT u.id,o.user_id,u.faculty_id,
  CASE WHEN u.role='moderator' THEN '["content.moderate"]'::jsonb
    ELSE '["content.moderate","resource.manage","announcement.publish","student.support","feedback.manage","channel.manage"]'::jsonb END,
  CURRENT_TIMESTAMP::text
FROM users u CROSS JOIN platform_owner o
WHERE u.role IN ('faculty_admin','moderator') AND u.faculty_id IS NOT NULL;
CREATE TABLE administrative_audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INTEGER NOT NULL REFERENCES users(id), action TEXT NOT NULL,
  target_type TEXT NOT NULL, target_id TEXT, details JSONB NOT NULL DEFAULT '{}', created_at TEXT NOT NULL
);
CREATE INDEX audit_actor_time ON administrative_audit(actor_id,created_at DESC);
CREATE TABLE xp_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id), category TEXT NOT NULL CHECK(category IN ('reading','help','practice','contribution')),
  event_key TEXT NOT NULL, points INTEGER NOT NULL CHECK(points BETWEEN 1 AND 100),
  status TEXT NOT NULL DEFAULT 'valid' CHECK(status IN ('valid','revoked')),
  actor_id INTEGER REFERENCES users(id), details JSONB NOT NULL DEFAULT '{}', created_at TEXT NOT NULL,
  UNIQUE(user_id,event_key)
);
CREATE INDEX xp_valid_user ON xp_events(user_id) WHERE status='valid';
