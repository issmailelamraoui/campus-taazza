export function translate(lang, key, fallback) {
  const dictionary = dictionaries[lang] || dictionaries.fr;
  const source = fallback ?? dictionaries.fr[key] ?? key;
  // A French source match wins so reused keys cannot mistranslate a different phrase.
  const translated = dictionary[source] ?? normalizedDictionaries[lang]?.[normalize(source)];
  if (translated !== undefined) return translated;
  // Future shared field validators and HTTP errors still get a localized message.
  if (/^.+ invalides?\.$/.test(source)) return {fr: source, ar: 'الرجاء التحقق من القيمة المدخلة.', en: 'Please check the entered value.'}[lang] || source;
  const status = /^Erreur (\d{3})$/.exec(source)?.[1];
  if (status) return {fr: `Une erreur est survenue (${status}). Réessayez.`, ar: `حدث خطأ (${status}). أعد المحاولة.`, en: `An error occurred (${status}). Please try again.`}[lang] || source;
  return dictionary[key] ?? source;
}
